"""Failure Codes and Severity definitions for LQMS AI Agent Evaluation.
"""

from enum import Enum
from typing import NamedTuple


class Severity(str, Enum):
    CRITICAL = "CRITICAL"
    HIGH = "HIGH"
    MEDIUM = "MEDIUM"
    LOW = "LOW"


class FailureCode(str, Enum):
    FACT_INVENTION = "FACT_INVENTION"
    UNSUPPORTED_ROOT_CAUSE = "UNSUPPORTED_ROOT_CAUSE"
    PREMATURE_ROOT_CAUSE = "PREMATURE_ROOT_CAUSE"
    HUMAN_BLAME_WITHOUT_EVIDENCE = "HUMAN_BLAME_WITHOUT_EVIDENCE"
    FIVEWHY_PASSES_EVIDENCE_BOUNDARY = "5WHY_PASSES_EVIDENCE_BOUNDARY"
    MISSING_EVIDENCE_REQUIREMENT = "MISSING_EVIDENCE_REQUIREMENT"
    MISSING_COMPETING_HYPOTHESIS = "MISSING_COMPETING_HYPOTHESIS"
    PREMATURE_CAPA = "PREMATURE_CAPA"
    UNSUPPORTED_IMPACT = "UNSUPPORTED_IMPACT"
    OVERCONFIDENT_OUTPUT = "OVERCONFIDENT_OUTPUT"
    OBSERVATION_MISCLASSIFICATION = "OBSERVATION_MISCLASSIFICATION"
    INCONSISTENT_REASONING = "INCONSISTENT_REASONING"
    IRRELEVANT_HYPOTHESIS = "IRRELEVANT_HYPOTHESIS"
    MISSING_CONTAINMENT = "MISSING_CONTAINMENT"
    OTHER = "OTHER"


class FailureRecord(NamedTuple):
    finding_id: str
    failure_code: FailureCode
    severity: Severity
    explanation: str
    expected_behavior: str
    actual_output: str
