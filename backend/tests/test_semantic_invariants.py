# ---------------------------------------------------------------------------
# PROPERTY 9: affected_object cannot be generated by more than one semantic
# producer -- verified by checking that _derive_deterministic_impact
# consumes canonical.finding_subject rather than recomputing it whenever
# canonical provides one, across several distinct subjects.
# ---------------------------------------------------------------------------

@pytest.mark.parametrize("subject,finding_text", [
    ("balance BAL-014", "The balance BAL-014 was used after certificate expiry."),
    ("temperature log for refrigerator QC-REF-02", "The temperature log for refrigerator QC-REF-02 was incomplete."),
    ("daily equipment inspection checklist", "The daily equipment inspection checklist was not completed."),
])
def test_affected_object_always_traces_to_canonical_subject(subject, finding_text):
    from app.agent.nodes.core_synthesis import _derive_deterministic_impact
    canonical = CanonicalFindingState(
        raw_finding=finding_text, observed_deviation="x", finding_subject=subject,
    )
    impact, clean_noun, _, _ = _derive_deterministic_impact(finding_text, canonical, "x")
    assert clean_noun == subject
    assert impact.affected_object.lower() == subject.lower()


# ---------------------------------------------------------------------------
# PROPERTY 10: process_at_risk must not be reconstructed from
# affected_object's first noun alone.
# ---------------------------------------------------------------------------

def test_process_at_risk_not_derived_from_affected_object_first_noun():
    """"Balance BAL-014" as the entity must not produce a process name
    starting with "Balance" when the finding's own deviation names a
    different control domain (calibration)."""
    from app.agent.nodes.core_synthesis import _derive_deterministic_impact
    finding = (
        "During the audit, the calibration certificate for balance BAL-014 showed an "
        "expiry date of 10 August 2026. The balance was used for three production "
        "measurements on 12 August 2026."
    )
    canonical = CanonicalFindingState(raw_finding=finding, observed_deviation="x", finding_subject="balance BAL-014")
    impact, _, _, _ = _derive_deterministic_impact(finding, canonical, "x")
    assert not impact.process_at_risk.lower().startswith("balance")
    assert "calibration" in impact.process_at_risk.lower()


# ---------------------------------------------------------------------------
# PROPERTY 15: LLM provenance IDs must belong to the evidence ledger --
# already covered directly in test_llm_synthesis_boundary.py's Test 5/6;
# this adds the boundary case of a hypothesis mixing one valid and one
# invalid ID in the same list (not just all-invalid).
# ---------------------------------------------------------------------------

@pytest.mark.asyncio
async def test_hypothesis_with_partially_invalid_provenance_is_rejected():
    import json
    from unittest.mock import AsyncMock, patch
    from app.agent.nodes.core_synthesis import core_synthesis_node
    from app.models.agent import InvestigateRequest

    finding = "The required inspection was not completed. The technician stated the gauge was broken."
    ledger = [
        EvidenceItem(claim="The required inspection was not completed.", source="finding_text", status=EvidenceStatus.VERIFIED),
        EvidenceItem(claim="The technician stated the gauge was broken.", source="finding_text", status=EvidenceStatus.REPORTED),
    ]
    state = {
        "request": InvestigateRequest(finding_text=finding),
        "evidence_ledger": ledger,
        "canonical_finding_state": CanonicalFindingState(raw_finding=finding, observed_deviation="x", finding_subject="inspection"),
        "investigation_plan": None, "trace": [], "errors": [],
    }
    bad_json = json.dumps({
        "root_cause": {
            "status": "NOT_ESTABLISHED", "category": "TO_BE_CONFIRMED", "statement": None,
            "candidate_hypotheses": [{
                "id": "H1", "name": "MIXED_PROVENANCE",
                "statement": "The gauge malfunction combined with an unrecorded event prevented inspection.",
                "status": "POSSIBLE",
                # C1 is real, C99 is not -- the whole hypothesis must be rejected,
                # not silently accepted because one of the two IDs is valid.
                "supporting_claim_ids": ["C1", "C99"], "contradicting_claim_ids": [],
                "evidence_needed": "record",
            }],
            "narrative": "x",
        },
        "five_why": {"steps": [], "is_complete": False, "status_note": "x"},
        "contributing_factors": [],
    })
    with patch("app.agent.nodes.core_synthesis.get_llm_client") as mock_get:
        mock_client = AsyncMock()
        mock_client.chat_completion.return_value = bad_json
        mock_get.return_value = mock_client
        result = await core_synthesis_node(state)
    assert "MIXED_PROVENANCE" not in [h.name for h in result["root_cause"].candidate_hypotheses]


