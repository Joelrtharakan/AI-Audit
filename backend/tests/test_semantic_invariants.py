@pytest.mark.asyncio
async def test_checklist_revision_survives_hypothesis_demotion_with_questions_intact():
    """Live-discovered gap: the knowledge/revision-gap branch's ONE
    investigation question was bound to H1 via hypothesis_tested. When the
    causal-proposition eligibility layer correctly demotes H1 (no claim
    directly supports the hedged communication-gap mechanism), the
    ID-consistency firewall stripped that question too, leaving ZERO
    investigation content despite real unresolved uncertainty (Property 6).
    Neutral, non-hypothesis-bound questions must survive this demotion."""
    from app.agent.nodes.final_evidence_verification import final_evidence_verification_node
    from app.agent.nodes.plan_investigation_fallback import build_deterministic_investigation_plan

    finding = (
        "The daily equipment inspection checklist was not completed for three consecutive days. "
        "The operator stated that they were unaware that the checklist procedure had been revised."
    )
    ledger = [
        EvidenceItem(claim="The daily equipment inspection checklist was not completed for three consecutive days.",
                     source="finding_text", status=EvidenceStatus.VERIFIED),
        EvidenceItem(claim="The operator stated that they were unaware that the checklist procedure had been revised.",
                     source="finding_text", status=EvidenceStatus.REPORTED),
    ]
    hyps, plan = build_deterministic_investigation_plan(finding, ledger)
    assert len(plan.questions) >= 2
    assert any(q.hypothesis_tested is None for q in plan.questions)

    mock_state = {
        "request": type("Request", (), {"finding_text": finding})(),
        "evidence_ledger": ledger,
        "canonical_finding_state": CanonicalFindingState(
            raw_finding=finding, observed_deviation="checklist not completed",
            finding_subject="daily equipment inspection checklist",
        ),
        "root_cause": type("RC", (), {
            "narrative": None, "statement": None, "status": "NOT_ESTABLISHED",
            "category": "TO_BE_CONFIRMED", "candidate_hypotheses": hyps,
        })(),
        "investigation_plan": plan,
        "capa_analysis": CapaAnalysis(status=CapaStatus.INVESTIGATION_REQUIRED, conditional_actions=[]),
        "ca_draft": None,
        "trace": [],
        "errors": [],
    }
    result = await final_evidence_verification_node(mock_state)
    inv = result["investigation_plan"]
    assert inv.questions, "Investigation questions must survive even if H1 is demoted"
